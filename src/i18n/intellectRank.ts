export function intellectRankOf(level: number, lang: Lang): string {
  const ranks = INTELLECT_RANK_TITLES[lang]
  const n = Math.max(1, Math.floor(level))
  const cycle = Math.floor((n - 1) / ranks.length)
  const name = ranks[(n - 1) % ranks.length] ?? ranks[0]
  return cycle === 0 ? name : `${name} (${cycle})`
}
