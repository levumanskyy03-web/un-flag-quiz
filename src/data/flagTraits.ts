export function flagTraits(iso: string): FlagTraits {
  const raw = RAW[iso] ?? 'w|'
  const [colorPart = '', motifPart = ''] = raw.split('|')
  const colors = [...new Set(colorPart.split(',').map((key) => COLOR[key]).filter((item): item is FlagColor => Boolean(item)))]
  const motifs = [
    ...new Set(
      motifPart
        .split(',')
        .map((key) => MOTIF[key.trim()])
        .filter((item): item is FlagMotif => Boolean(item)),
    ),
  ]
  return { colors, motifs }
}
