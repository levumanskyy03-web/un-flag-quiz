const EASY_BY_MODE: Record<string, ReadonlySet<string> | 'flag'> = {
  flagToName: 'flag',
  nameToFlag: 'flag',
  nameToCapital: CAPITAL_EASY,
  nameToCurrency: CURRENCY_EASY,
  nameToPopulation: POPULATION_EASY,
  nameToFounded: FOUNDED_EASY,
  neighborsToName: NEIGHBORS_EASY,
  nameToMap: MAP_FIND_EASY,
  mapToName: MAP_IDENTIFY_EASY,
}

export function isEasyForMode(country: Country, mode: string): boolean {
  const easy = EASY_BY_MODE[mode]
  if (!easy || easy === 'flag') return country.difficulty === 'easy'
  return easy.has(country.iso)
}
