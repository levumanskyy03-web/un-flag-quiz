export const GOVERNMENT: Record<string, GovKind> = Object.fromEntries(
  (Object.entries(BY_KIND) as Array<[GovKind, readonly string[]]>).flatMap(([kind, isos]) =>
    isos.map((iso) => [iso, kind]),
  ),
)

const missing = COUNTRIES.filter((country) => !GOVERNMENT[country.iso]).map((country) => country.iso)
if (missing.length > 0) {
  throw new Error(`Missing government type for: ${missing.join(', ')}`)
}

export function govKindOf(iso: string): GovKind | undefined {
  return GOVERNMENT[iso]
}
