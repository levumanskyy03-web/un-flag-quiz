export function waterCutsLand(id: string): boolean {
  return SHAPES[id]?.cutLand ?? true
}

export function waterShapePath(id: string): string {
  const shape = SHAPES[id]
  const lines = RIVER_LINES[id]
  const closed = shape ? shape.rings.map(ringPath).join(' ') : ''
  const open = lines ? lines.map(linePath).join(' ') : ''
  return [closed, open].filter(Boolean).join(' ')
}

export function waterShapeCamera(id: string): Camera | undefined {
  const shape = SHAPES[id]
  const lines = RIVER_LINES[id]
  const lonlats = [...(shape?.rings.flat() ?? []), ...(lines?.flat() ?? [])]
  if (lonlats.length === 0) return undefined
  const points = lonlats.map(([lon, lat]) => lonLatToMap(lon, lat))
  let minX = Infinity
  let minY = Infinity
  let maxX = -Infinity
  let maxY = -Infinity
  for (const point of points) {
    minX = Math.min(minX, point.x)
    minY = Math.min(minY, point.y)
    maxX = Math.max(maxX, point.x)
    maxY = Math.max(maxY, point.y)
  }
  const isLine = Boolean(lines) && !shape
  const minSpan = isLine ? 52 : 28
  const width = Math.max(minSpan, maxX - minX)
  const height = Math.max(minSpan, maxY - minY)
  const pad = Math.max(width, height) * (isLine ? 0.28 : 0.18)
  return placeCamera({
    x: minX - pad - (width - (maxX - minX)) / 2,
    y: minY - pad - (height - (maxY - minY)) / 2,
    w: width + pad * 2,
    h: height + pad * 2,
  })
}
